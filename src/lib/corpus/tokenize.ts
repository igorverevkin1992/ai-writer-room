/**
 * Токенизация для локального поиска по корпусу.
 *
 * Никаких эмбеддингов и внешних сервисов: корпус первоисточников не должен
 * покидать машину. Русская морфология снимается лёгким отсечением окончаний —
 * это не лингвистика, а нормализация ключей для BM25.
 */

const RU_SUFFIXES = [
  'иями', 'ями', 'ами', 'ыми', 'ими', 'ого', 'ему', 'ому', 'ыми', 'его',
  'ает', 'ают', 'ует', 'уют', 'ить', 'ать', 'ять', 'еть', 'ся', 'сь',
  'ями', 'иях', 'ах', 'ях', 'ов', 'ев', 'ий', 'ый', 'ой', 'ая', 'яя',
  'ое', 'ее', 'ые', 'ие', 'ую', 'юю', 'ам', 'ям', 'ом', 'ем', 'ах',
  'ла', 'ло', 'ли', 'ть', 'ет', 'ут', 'ют', 'ат', 'ят', 'ешь', 'ишь',
  'а', 'я', 'о', 'е', 'ы', 'и', 'у', 'ю', 'ь', 'й',
].sort((a, b) => b.length - a.length);

const EN_SUFFIXES = ['ing', 'edly', 'ies', 'ied', 'es', 'ed', 's'].sort((a, b) => b.length - a.length);

const STOPWORDS = new Set([
  'и','в','во','не','что','он','на','я','с','со','как','а','то','все','она','так','его','но','да',
  'ты','к','у','же','вы','за','бы','по','только','ее','мне','было','вот','от','меня','еще','нет',
  'о','из','ему','когда','даже','ну','вдруг','ли','если','уже','или','ни','быть','был','него','до',
  'вас','опять','уж','вам','ведь','там','потом','себя','ничего','ей','они','тут','где','есть','надо',
  'ней','для','мы','тебя','их','чем','была','сам','чтоб','без','этот','того','потому','этого','какой',
  'ним','здесь','этом','один','почти','мой','тем','чтобы','нее','были','куда','зачем','всех','можно',
  'при','два','об','другой','хоть','после','над','больше','тот','через','эти','нас','про','всего',
  'них','какая','много','разве','три','эту','моя','свою','этой','перед','иногда','лучше','чуть','том',
  'нельзя','такой','им','более','всегда','конечно','всю','между','это','эта',
  'the','a','an','of','to','in','is','it','and','or','that','this','for','on','as','with','by','be',
  'are','was','were','you','your','they','their','from','at','not','but','have','has','had','we','he',
  'she','his','her','its','will','can','if','so','what','which','who','how','when','than','then',
]);

export function stem(word: string): string {
  const w = word.toLowerCase();
  if (w.length <= 4) return w;
  const suffixes = /[а-яё]/.test(w) ? RU_SUFFIXES : EN_SUFFIXES;
  for (const suffix of suffixes) {
    if (w.length - suffix.length >= 4 && w.endsWith(suffix)) return w.slice(0, -suffix.length);
  }
  return w;
}

export function tokenize(text: string): string[] {
  return (text || '')
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .split(/\s+/)
    .filter((w) => w.length > 2 && !STOPWORDS.has(w))
    .map(stem);
}
